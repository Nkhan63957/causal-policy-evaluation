        if row['min_wage'] > fed_mw:
            pct_above    = (row['min_wage'] - fed_mw) / fed_mw
            emp_effect   = 1 + (MW_ELASTICITY * pct_above)
            panel.loc[i, 'employment'] = panel.loc[i, 'employment'] * emp_effect
